// 從模型輸出裡抓第一個 JSON 陣列。黑話學習與其他背景解析共用。
export function extractJsonArray(text) {
  const raw = String(text ?? '').trim();
  if (!raw) return null;
  try {
    const direct = JSON.parse(raw);
    if (Array.isArray(direct)) return direct;
  } catch {}
  if (raw.length > 400_000) return null;
  const MAX_CANDIDATES = 32;
  // 掃描次數也要有上限：一整篇都是 `[` 時，外層會對每個 `[` 掃到串尾，
  // 實測 10 萬個 `[` 能卡住事件循環 10 秒以上。
  let attempts = 0;
  const MAX_SCAN_ATTEMPTS = 64;
  const candidates = [];
  for (let i = 0; i < raw.length; i += 1) {
    if (raw[i] !== '[') continue;
    if (candidates.length >= MAX_CANDIDATES || attempts >= MAX_SCAN_ATTEMPTS) break;
    attempts += 1;
    let depth = 0;
    let inString = false;
    let escaped = false;
    for (let j = i; j < raw.length; j += 1) {
      const c = raw[j];
      if (inString) {
        if (escaped) escaped = false;
        else if (c === '\\') escaped = true;
        else if (c === '"') inString = false;
        continue;
      }
      if (c === '"') { inString = true; continue; }
      if (c === '[') depth += 1;
      else if (c === ']') {
        depth -= 1;
        if (depth === 0) {
          candidates.push(raw.slice(i, j + 1));
          break;
        }
      }
    }
  }
  let fallback = null;
  for (const candidate of candidates) {
    let parsed;
    try {
      parsed = JSON.parse(candidate);
    } catch {
      continue;
    }
    if (!Array.isArray(parsed)) continue;
    if (parsed.some((item) => item && typeof item === 'object' && !Array.isArray(item))) return parsed;
    if (fallback === null) fallback = parsed;
  }
  return fallback;
}
